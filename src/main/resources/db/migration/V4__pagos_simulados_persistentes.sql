CREATE UNIQUE INDEX ventas_tienda_pago_uq ON public.ventas(tienda_id, id_venta);
CREATE TABLE public.pagos_proveedor_configuracion (
    tienda_id BIGINT NOT NULL REFERENCES public.tiendas(id),
    proveedor TEXT NOT NULL CHECK (proveedor='SANDBOX'),
    habilitado BOOLEAN NOT NULL DEFAULT false,
    modo TEXT NOT NULL DEFAULT 'SANDBOX' CHECK (modo='SANDBOX'),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(tienda_id, proveedor)
);
CREATE TABLE public.pagos_simulados (
    id UUID PRIMARY KEY,
    tienda_id BIGINT NOT NULL REFERENCES public.tiendas(id),
    id_venta INTEGER NOT NULL,
    proveedor TEXT NOT NULL DEFAULT 'SANDBOX' CHECK (proveedor='SANDBOX'),
    clave_idempotencia VARCHAR(200) NOT NULL,
    importe NUMERIC(12,2) NOT NULL CHECK (importe > 0),
    moneda VARCHAR(3) NOT NULL CHECK (moneda='PEN'),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','APROBADO','RECHAZADO','EXPIRADO','REEMBOLSADO')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY(tienda_id,id_venta) REFERENCES public.ventas(tienda_id,id_venta),
    UNIQUE(tienda_id, clave_idempotencia),
    UNIQUE(tienda_id, id_venta)
);
CREATE TABLE public.pagos_simulados_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id UUID NOT NULL REFERENCES public.pagos_simulados(id),
    estado VARCHAR(20) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(pago_id, estado)
);
