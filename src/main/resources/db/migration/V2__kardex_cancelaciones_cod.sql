-- Revisar contra el esquema existente antes de aplicar fuera de Testcontainers.
-- Falla si existe una tabla homonima para evitar aceptar un contrato incompatible.
CREATE TABLE public.inventario_kardex (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    id_venta INTEGER NOT NULL,
    id_producto_talla INTEGER NOT NULL REFERENCES public.producto_tallas(id_producto_talla),
    tipo VARCHAR(20) NOT NULL CHECK (tipo = 'ENTRADA'),
    origen VARCHAR(40) NOT NULL CHECK (origen = 'CANCELACION_COD'),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    stock_anterior INTEGER NOT NULL CHECK (stock_anterior >= 0),
    stock_posterior INTEGER NOT NULL CHECK (stock_posterior >= 0),
    motivo VARCHAR(300) NOT NULL,
    operador TEXT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (stock_posterior::BIGINT = stock_anterior::BIGINT + cantidad::BIGINT),
    FOREIGN KEY (tienda_id, id_venta)
        REFERENCES public.saas_cancelaciones_cod(tienda_id, id_venta),
    UNIQUE (tienda_id, id_venta, id_producto_talla, origen)
);
CREATE INDEX inventario_kardex_tienda_fecha ON public.inventario_kardex(tienda_id, creado_en);
